SYSTEM_PROMPT_BASE = """You are an elite investment analyst at a top-tier institutional investment firm.
You write professional, objective, data-driven narratives for investment due diligence memorandums.

CRITICAL RULES:
1. NEVER invent, estimate, or hallucinate any financial numbers. You may ONLY reference numbers
   that are explicitly provided to you in the data below.
2. Write in a professional, third-person, institutional tone.
3. Be balanced — acknowledge both strengths and risks.
4. Use specific data points from the provided context to support every claim.
5. Do NOT use markdown formatting (no **, ##, etc.). Write plain HTML-ready text.
6. Write in complete, well-structured paragraphs (not bullet points).
7. Each paragraph should be 3-5 sentences long.
"""


def generate_executive_summary_narrative(data: dict) -> str:
    """Generate the 3-4 paragraph key findings narrative for the Executive Summary.

    Args:
        data: Dict containing qoe_summary, risk_assessment, market_intel, company info.

    Returns:
        HTML-formatted narrative string.
    """
    user_prompt = f"""
Write a 3-4 paragraph executive summary narrative for an Investment Due Diligence Memorandum.

COMPANY: {data.get('company_name', 'N/A')} ({data.get('ticker', 'N/A')})
INDUSTRY: {data.get('industry_name', 'N/A')}

KEY DATA POINTS:
- Earnings Quality Score: {data.get('qoe_score', 'N/A')}/100 ({data.get('qoe_label', 'N/A')})
- Composite Risk Score: {data.get('risk_score', 'N/A')}/100 (Level: {data.get('risk_level', 'N/A')})
- Investment Stance: {data.get('investment_stance', 'N/A')}
- Deal Breakers Triggered: {data.get('deal_breakers_triggered', 0)} of 8
- Competitive Position: {data.get('competitive_position', 'N/A')}
- Moat Width: {data.get('moat_width', 'N/A')}
- Current Price: ${data.get('current_price', 'N/A')}
- Market Cap: {data.get('market_cap_display', 'N/A')}

TOP STRENGTHS: {data.get('top_strengths', 'N/A')}
TOP CONCERNS: {data.get('top_concerns', 'N/A')}
KEY ADVANTAGES: {data.get('key_advantages', 'N/A')}
KEY VULNERABILITIES: {data.get('key_vulnerabilities', 'N/A')}

PARAGRAPH STRUCTURE:
1. Financial Health — Quality of Earnings assessment, key financial strengths/weaknesses
2. Competitive Position — Market standing, moat assessment, competitive advantages
3. Risk Profile — Overall risk level, deal breakers, key risk areas
4. Investment Conclusion — Synthesize the above into a clear investment thesis statement

Wrap each paragraph in <p> tags.
"""
    return _call_llm(SYSTEM_PROMPT_BASE, user_prompt)


