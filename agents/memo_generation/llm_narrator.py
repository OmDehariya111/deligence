"""
Module:  llm_narrator.py
Agent:   Memo Generation Agent
Purpose: LLM narrative generation wrapper for professional investment memo paragraphs.
         Uses Gemini 2.5 Pro (via LiteLLM + Vertex AI) for ALL narrative generation.
         NO financial numbers are generated by LLM — only professional text narratives.
Inputs:  Structured data dicts from data_collector, section context.
Outputs: Professional narrative text strings.
"""

import logging
import time
import re
from typing import Any

import litellm
from dotenv import load_dotenv

load_dotenv()

# Disable litellm's internal retries — we handle retries ourselves
litellm.num_retries = 0

logger = logging.getLogger(__name__)

# All memo generation uses Gemini 2.5 Pro for best quality
DEFAULT_MODEL = "vertex_ai/gemini-2.5-pro"


def _call_llm(system_prompt: str, user_prompt: str, max_retries: int = 3,
              temperature: float = 0.3) -> str:
    """Call LLM with retry logic and return the text response.

    Args:
        system_prompt: System-level instructions for the LLM.
        user_prompt: User-level prompt with data and instructions.
        max_retries: Maximum retry attempts on failure.
        temperature: LLM temperature (lower = more deterministic).

    Returns:
        The LLM's text response, or empty string on failure.
    """
    for attempt in range(max_retries):
        try:
            response = litellm.completion(
                model=DEFAULT_MODEL,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=temperature,
                max_tokens=4096,
                num_retries=0,
            )
            text = response.choices[0].message.content
            if text:
                logger.info(f"LLM call successful (attempt {attempt + 1}, "
                            f"tokens: {response.usage.total_tokens})")
                return text.strip()
            logger.warning(f"LLM returned empty response on attempt {attempt + 1}")
        except Exception as e:
            wait = 2 ** attempt + 1
            logger.warning(f"LLM call failed (attempt {attempt + 1}/{max_retries}): {e}. "
                           f"Retrying in {wait}s...")
            time.sleep(wait)

    logger.error(f"LLM call failed after {max_retries} attempts")
    return ""


